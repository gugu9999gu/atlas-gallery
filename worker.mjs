const SECURITY = {
  'X-Content-Type-Options': 'nosniff',
  'Referrer-Policy': 'strict-origin-when-cross-origin',
  'X-Frame-Options': 'SAMEORIGIN',
  'Permissions-Policy': 'camera=(), microphone=(), geolocation=()',
  'Content-Security-Policy': "default-src 'self'; script-src 'self' 'unsafe-inline'; style-src 'self' 'unsafe-inline'; img-src 'self' data: blob:; connect-src 'self'; font-src 'self'; object-src 'none'; base-uri 'self'; frame-ancestors 'self'; frame-src 'none'; form-action 'self'; upgrade-insecure-requests"
};
export default {
  async fetch(request, env, ctx) {
    if (!['GET', 'HEAD'].includes(request.method)) return new Response('Method not allowed', {status: 405, headers: {...SECURITY, Allow: 'GET, HEAD'}});
    const url = new URL(request.url);
    if (url.protocol !== 'https:') {url.protocol = 'https:'; return Response.redirect(url.toString(), 301);}
    if (url.pathname === '/index.html') {url.pathname = '/'; return Response.redirect(url.toString(), 301);}
    let path;
    try {path = decodeURIComponent(url.pathname);} catch {return new Response('Invalid path', {status: 400, headers: SECURITY});}
    if (path === '/') path = '/index.html';
    else if (!FILES[path] && FILES[path + '.html']) path += '.html';
    const found = Object.hasOwn(FILES, path);
    if (!found) path = '/404.html';
    // Query state is client-side only; use one cache entry per file and release.
    const cacheURL = new URL(url.origin + path);
    cacheURL.search = '?atlas-version=3.1.0';
    const key = new Request(cacheURL, {method: 'GET'});
    let response = found ? await caches.default.match(key) : null;
    if (!response) {
      const object = await env.STATIC.get(path.slice(1));
      if (!object) return new Response('Reference temporarily unavailable', {status: 503, headers: {...SECURITY, 'Cache-Control': 'no-store', 'Retry-After': '30'}});
      const headers = new Headers(SECURITY);
      headers.set('Content-Type', FILES[path] || 'text/html; charset=utf-8');
      headers.set('ETag', object.httpEtag);
      headers.set('Last-Modified', object.uploaded.toUTCString());
      headers.set('Cache-Control', found ? 'public, max-age=300, stale-while-revalidate=600' : 'no-store');
      headers.set('X-Atlas-Version', '3.1.0');
      headers.set('Content-Length', String(object.size));
      if (!found) headers.set('X-Robots-Tag', 'noindex');
      response = new Response(object.body, {status: found ? 200 : 404, headers});
      if (found && request.method === 'GET') ctx.waitUntil(caches.default.put(key, response.clone()));
    }
    if (found && request.headers.get('If-None-Match') === response.headers.get('ETag')) {
      const headers = new Headers(response.headers); headers.delete('Content-Length');
      return new Response(null, {status: 304, headers});
    }
    return request.method === 'HEAD' ? new Response(null, {status: response.status, headers: response.headers}) : response;
  }
};
